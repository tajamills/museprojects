// Embeds the Quietly Ready interactive worksheets (.docx) into the server
// bundle as base64. The server is built into a single dist/server.js with
// esbuild, so a loose file on disk would not reliably ship — the generated
// TS module below is imported by server/src/index.ts and inlined at build
// time. Source of truth: ~/workspace/abisola-books/files/
// quietly-ready-worksheets.docx (interactive Word file, Oct 29, 2026).
// Run: node scripts/build-worksheets.mjs (re-run whenever the docx changes)
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const HOME = process.env.HOME ?? "/home/hatch";
const src = path.join(HOME, "workspace/abisola-books/files/quietly-ready-worksheets.docx");
const out = path.join(root, "server/src/worksheets-data.ts");

const buf = await readFile(src);
const b64 = buf.toString("base64");
const wrapped = b64.match(/.{1,100}/g).map((chunk) => `"${chunk}"`).join(" +\n");

await writeFile(
  out,
  `// GENERATED by scripts/build-worksheets.mjs — do not edit by hand.\n` +
    `// Base64 of quietly-ready-worksheets.docx (${buf.length} bytes), the\n` +
    `// interactive Quietly Ready worksheets served to book owners only.\n` +
    `export const WORKSHEETS_DOCX_BASE64 =\n${wrapped};\n`,
);
console.log(`[build-worksheets] wrote ${out} from ${src} (${buf.length} bytes)`);
